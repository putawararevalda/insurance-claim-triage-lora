def main():
    parser = argparse.ArgumentParser(description="Run Phase 2.3 Hyperparameter Sweep.")
    parser.add_argument("--config", type=str, default="configs/sweep_config.yaml", help="Path to sweep config YAML")
    parser.add_argument("--tracker", type=str, default=os.environ.get("TRACKER", "wandb"), help="Tracker: wandb, mlflow, none")
    parser.add_argument("--smoke_test", action="store_true", help="Run 6-step smoke test for each configuration")
    parser.add_argument("--max_runs", type=int, default=4, help="Maximum number of runs to execute")
    parser.add_argument("--num_val_samples", type=int, default=2, help="Number of validation inference samples per epoch")
    args = parser.parse_args()

    config = load_sweep_config(args.config)
    base_model = config.get("base_model", "Qwen/Qwen2.5-1.5B-Instruct")
    train_file = config.get("dataset", {}).get("train_file", "data/alpha_train.jsonl")
    val_file = config.get("dataset", {}).get("val_file", "data/alpha_val.jsonl")
    runs_to_execute = config.get("runs", [])[:args.max_runs]

    print("\n" + "=" * 80)
    print(f"  STARTING PHASE 2.3 HYPERPARAMETER SWEEP ({len(runs_to_execute)} RUNS)")
    print(f"  Base Model  : {base_model}")
    print(f"  Tracker     : {args.tracker}")
    print(f"  Smoke Test  : {args.smoke_test}")
    print("=" * 80)

    sweep_start = time.time()
    results = []

    for run_def in runs_to_execute:
        res = run_single_experiment(
            run_def=run_def,
            base_model=base_model,
            train_file=train_file,
            val_file=val_file,
            tracker=args.tracker,
            smoke_test=args.smoke_test,
            num_val_samples=args.num_val_samples,
        )
        results.append(res)

    total_sweep_time = time.time() - sweep_start
    print("\n" + "=" * 80)
    print(f"[ALL COMPLETE] ALL {len(results)} SWEEP EXPERIMENTS COMPLETED in {total_sweep_time/60:.2f} minutes!")
    print("=" * 80)

    # Determine best run (lowest best_eval_loss)
    best_run = min(results, key=lambda x: x["best_eval_loss"] if x["best_eval_loss"] is not None else 999.0)
    print(f"\n[WINNER / GOLDEN ADAPTER]: {best_run['run_id']} ({best_run['name']})")
    print(f"   Best Eval Loss : {best_run['best_eval_loss']:.4f}")
    print(f"   Peak VRAM      : {best_run['peak_vram_gb']:.2f} GB")
    print(f"   Training Time  : {best_run['train_duration_min']:.2f} min")

    # Save consolidated JSON summary
    summary_path = "logs/sweep_summary_all.json"
    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump({
            "total_runs": len(results),
            "total_sweep_duration_min": round(total_sweep_time / 60.0, 2),
            "best_run": best_run,
            "all_runs": results,
        }, f, indent=2, ensure_ascii=False)
    print(f"Saved consolidated summary to: {summary_path}")

    # Export Golden Adapter
    export_golden_adapter(best_run, destination_dir="models/lora_adapter_alpha_best")

    # Generate Markdown Report
    generate_analysis_report(results, best_run, report_path="reports/sweep_alpha_analysis.md")

    print("\n" + "=" * 80)
    print("[SUCCESS] PHASE 2.3 SWEEP AND SELECTION COMPLETED SUCCESSFULLY!")
    print("=" * 80)


if __name__ == "__main__":
    main()
